"""Agent harness adapters: L1 content → L2 files, idempotency and drift checks."""

from __future__ import annotations

from pathlib import Path

import pytest

from bacmap.agent import harnesses, roledef


def test_core_harnesses_are_listed():
    names = {spec.name for spec in harnesses.list_harnesses()}
    assert {"hermes", "pi", "dsh", "codex", "opencode", "generic"} <= names


def test_instructions_are_generated_from_bacmap_content():
    spec = harnesses.get_harness("pi")
    text = harnesses.instructions_markdown(spec)
    assert harnesses.GENERATED_MARKER in text
    assert "bacmap_role_analyst" in text
    assert "skill://bacmap/analyst/SKILL.md" in text
    assert "Profile" in text
    assert "do not edit" in text


def test_external_prompt_does_not_claim_internal_permissions():
    internal = roledef.build_system_prompt("analyst")
    external = roledef.build_system_prompt("analyst", audience="external")
    assert "由代码强制" in internal
    assert "由代码强制" not in external
    assert "MCP" in external and "Profile" in external
    assert "角色说明书" in external


def test_external_audience_rejects_unknown_value():
    with pytest.raises(ValueError):
        roledef.build_system_prompt("analyst", audience="public")


def test_install_is_idempotent(tmp_path: Path):
    first = harnesses.install("pi", scope="project", target=tmp_path)
    second = harnesses.install("pi", scope="project", target=tmp_path)
    assert first.instructions == second.instructions
    assert Path(first.instructions).is_file()
    assert Path(first.manifest).is_file()
    report = harnesses.doctor(tmp_path)
    assert report.ok
    assert report.harness == "pi"


def test_install_refuses_to_overwrite_user_file(tmp_path: Path):
    user = tmp_path / ".hermes.md"
    user.write_text("my own notes\n", encoding="utf-8")
    with pytest.raises(harnesses.InstallError, match="refusing"):
        harnesses.install("hermes", scope="project", target=tmp_path)
    result = harnesses.install("hermes", scope="project", target=tmp_path, force=True)
    assert Path(result.instructions).read_text(encoding="utf-8").startswith(
        "<!-- generated by bacmap"
    )


def test_install_with_skills_writes_portable_skills(tmp_path: Path):
    result = harnesses.install(
        "generic", scope="project", target=tmp_path, with_skills=True
    )
    assert len(result.skills) == len(roledef.list_roles())
    assert (tmp_path / ".bacmap" / "skills" / "analyst" / "SKILL.md").is_file()


def test_doctor_detects_modified_file(tmp_path: Path):
    result = harnesses.install("dsh", scope="project", target=tmp_path)
    assert harnesses.doctor(tmp_path).ok
    Path(result.instructions).write_text("tampered\n", encoding="utf-8")
    report = harnesses.doctor(tmp_path)
    assert not report.ok
    assert any("modified file" in error for error in report.errors)


def test_doctor_without_manifest_is_not_ok(tmp_path: Path):
    report = harnesses.doctor(tmp_path)
    assert not report.ok
    assert "no install manifest" in report.errors[0]


def test_export_skill_unknown_role(tmp_path: Path):
    with pytest.raises(harnesses.InstallError, match="unknown role"):
        harnesses.export_skill("nope")
