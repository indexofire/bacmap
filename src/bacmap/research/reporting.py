"""STROBE-style reporting checklist and submission package.

The checklist is a deterministic draft. It tells a human which items still need evidence;
it never claims a manuscript is publication-ready by itself.
"""

from __future__ import annotations

import hashlib
import json
import shutil
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field

from bacmap.research.models import (
    AnalysisPlan,
    AnalysisSession,
    Claim,
    ClaimStatus,
    Cohort,
    CohortStatus,
    Experiment,
    ExperimentStatus,
    PlanStatus,
    Study,
)
from bacmap.research.publication import publication_readiness
from bacmap.research.store import ResearchObjectStore, ResearchStore

CHECKLIST_SCHEMA: Literal["bacmap.reporting_checklist/1"] = "bacmap.reporting_checklist/1"
PACKAGE_SCHEMA: Literal["bacmap.submission_package/1"] = "bacmap.submission_package/1"

Status = Literal["met", "partial", "missing", "not_applicable"]


class ChecklistItem(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    item_id: str
    section: str
    requirement: str
    status: Status
    evidence: list[str] = Field(default_factory=list)
    note: str = ""


class Checklist(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, populate_by_name=True)

    schema_name: Literal["bacmap.reporting_checklist/1"] = Field(
        default=CHECKLIST_SCHEMA, alias="schema"
    )
    study_id: str
    guideline: str = "STROBE"
    items: list[ChecklistItem]
    met: int
    partial: int
    missing: int


class PackageFile(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    kind: str
    source: str
    path: str
    sha256: str


class SubmissionPackage(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, populate_by_name=True)

    schema_name: Literal["bacmap.submission_package/1"] = Field(
        default=PACKAGE_SCHEMA, alias="schema"
    )
    study_id: str
    generated_at: str
    output_dir: str
    guideline: str = "STROBE"
    checklist: Checklist
    readiness: dict[str, Any]
    files: list[PackageFile]
    blockers: list[str]
    data_availability: str
    code_availability: str
    checklist_review: dict[str, Any] = Field(default_factory=dict)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _item(
    item_id: str,
    section: str,
    requirement: str,
    status: Status,
    evidence: list[str] | None = None,
    note: str = "",
) -> ChecklistItem:
    return ChecklistItem(
        item_id=item_id,
        section=section,
        requirement=requirement,
        status=status,
        evidence=evidence or [],
        note=note,
    )


def build_checklist(
    study: Study,
    cohorts: list[Cohort],
    plans: list[AnalysisPlan],
    claims: list[Claim],
    experiments: list[Experiment],
    sessions: list[AnalysisSession],
) -> Checklist:
    """Build a conservative STROBE draft from research objects (not a manuscript review)."""
    frozen_cohorts = [c for c in cohorts if c.status is CohortStatus.FROZEN]
    frozen_plans = [p for p in plans if p.status is PlanStatus.FROZEN]
    approved_claims = [
        c
        for c in claims
        if c.status in {ClaimStatus.SUPPORTED, ClaimStatus.APPROVED_FOR_EXPORT}
    ]
    executed = [
        e
        for e in experiments
        if e.status in {ExperimentStatus.SUCCESS, ExperimentStatus.NEGATIVE}
    ]
    run_ids = sorted({run for e in experiments for run in e.run_ids})
    members = sum(len(c.members) for c in frozen_cohorts)

    items = [
        _item(
            "1a",
            "Title and abstract",
            "Indicate the study design in the title or abstract",
            "partial" if study.question else "missing",
            [study.question] if study.question else [],
            "The agent/human must finalise the wording.",
        ),
        _item(
            "1b",
            "Title and abstract",
            "Provide an informative abstract",
            "missing",
            note="Not generated by the deterministic layer.",
        ),
        _item(
            "2",
            "Introduction",
            "Explain the scientific background and rationale",
            "partial" if study.question else "missing",
            [study.question] if study.question else [],
        ),
        _item(
            "3",
            "Introduction",
            "State pre-specified objectives and hypotheses",
            "met" if study.question else "missing",
            [study.question] if study.question else [],
        ),
        _item(
            "4",
            "Methods",
            "Present key elements of study design early",
            "partial" if frozen_plans else "missing",
            [p.plan_id for p in frozen_plans],
        ),
        _item(
            "5",
            "Methods",
            "Describe setting, locations and relevant dates",
            "partial" if study.pathogen_scope else "missing",
            [study.pathogen_scope] if study.pathogen_scope else [],
        ),
        _item(
            "6a",
            "Methods",
            "Give eligibility criteria and sources of participants",
            "met" if frozen_cohorts else "missing",
            [c.cohort_id for c in frozen_cohorts],
        ),
        _item(
            "6b",
            "Methods",
            "Describe matching or weighting procedures",
            "not_applicable",
            note="No matching/weighting is implemented in this slice.",
        ),
        _item(
            "7",
            "Methods",
            "Define all variables, outcomes and predictors",
            "partial" if frozen_plans else "missing",
            [p.plan_id for p in frozen_plans],
        ),
        _item(
            "8",
            "Methods",
            "Describe data sources and measurement",
            "met" if sessions else "partial" if run_ids else "missing",
            [s.session_id for s in sessions] + run_ids,
        ),
        _item(
            "9",
            "Methods",
            "Describe efforts to address bias",
            "missing",
            note="Bias assessment requires human review.",
        ),
        _item(
            "10",
            "Methods",
            "Explain how the study size was arrived at",
            "partial" if members else "missing",
            [f"{members} members in frozen cohorts"] if members else [],
            "Power/sample-size planning is not yet implemented.",
        ),
        _item(
            "11",
            "Methods",
            "Explain quantitative variables and statistical methods",
            "partial" if frozen_plans else "missing",
            [p.plan_id for p in frozen_plans],
            "Advanced models (mixed effects, IPTW, survival) are not yet implemented.",
        ),
        _item(
            "12",
            "Methods",
            "Describe subgroup and sensitivity analyses",
            "partial" if experiments else "missing",
            [e.experiment_id for e in experiments],
        ),
        _item(
            "13",
            "Results",
            "Report numbers at each stage of the study",
            "partial" if members else "missing",
            [f"cohort members={members}"] if members else [],
        ),
        _item(
            "14",
            "Results",
            "Give characteristics of participants and missing data",
            "partial" if sessions else "missing",
            [s.session_id for s in sessions],
        ),
        _item(
            "15",
            "Results",
            "Report outcome events and summary measures",
            "partial" if executed else "missing",
            [e.experiment_id for e in executed],
        ),
        _item(
            "16",
            "Results",
            "Report main results with effect estimates and precision",
            "partial" if approved_claims else "missing",
            [c.claim_id for c in approved_claims],
        ),
        _item(
            "17",
            "Results",
            "Report other analyses and sensitivity results",
            "partial" if experiments else "missing",
            [e.experiment_id for e in experiments],
        ),
        _item(
            "18",
            "Discussion",
            "Summarise key results with reference to objectives",
            "missing",
            note="Human/agent narrative required.",
        ),
        _item(
            "19",
            "Discussion",
            "Discuss limitations and bias",
            "missing",
            note="Human review required.",
        ),
        _item(
            "20",
            "Discussion",
            "Give a cautious overall interpretation",
            "missing",
            note="Human review required.",
        ),
        _item(
            "21",
            "Discussion",
            "Discuss generalisability",
            "missing",
            note="Human review required.",
        ),
        _item(
            "22",
            "Other",
            "State funding and conflicts of interest",
            "missing",
            note="Human review required.",
        ),
    ]
    met = sum(1 for item in items if item.status == "met")
    partial = sum(1 for item in items if item.status == "partial")
    missing = sum(1 for item in items if item.status == "missing")
    return Checklist(
        study_id=study.study_id,
        items=items,
        met=met,
        partial=partial,
        missing=missing,
    )


def checklist_for_study(home: Path | str, study_id: str) -> Checklist:
    """Load objects and build the deterministic checklist for one study."""
    with ResearchObjectStore(home) as store:
        try:
            study = store.get_study(study_id)
        except KeyError as exc:
            raise ValueError(f"no such study: {study_id}") from exc
        return build_checklist(
            study,
            store.list_cohorts(study_id),
            store.list_plans(study_id),
            store.list_claims(study_id),
            store.list_experiments(study_id),
            store.list_sessions_by_study(study_id),
        )


def checklist_markdown(checklist: Checklist) -> str:
    lines = [
        f"# STROBE checklist draft — {checklist.study_id}",
        "",
        "> Deterministic draft. A human must complete missing items and review the manuscript.",
        "",
        "| Item | Section | Requirement | Status | Evidence |",
        "|---|---|---|---|---|",
    ]
    for item in checklist.items:
        evidence = "; ".join(item.evidence) if item.evidence else item.note
        lines.append(
            f"| {item.item_id} | {item.section} | {item.requirement} | "
            f"{item.status} | {evidence} |"
        )
    lines.append("")
    return "\n".join(lines)


def build_submission_package(
    home: Path | str,
    study_id: str,
    out_dir: Path | str,
    *,
    checklist: Checklist | None = None,
    checklist_review: dict[str, Any] | None = None,
) -> SubmissionPackage:
    """Collect research artifacts and write a reproducible submission manifest."""
    home_path = Path(home)
    target = Path(out_dir).expanduser().resolve()
    target.mkdir(parents=True, exist_ok=True)
    artifacts_dir = target / "artifacts"
    artifacts_dir.mkdir(exist_ok=True)

    with ResearchObjectStore(home_path) as store:
        try:
            study = store.get_study(study_id)
        except KeyError as exc:
            raise ValueError(f"no such study: {study_id}") from exc
        cohorts = store.list_cohorts(study_id)
        plans = store.list_plans(study_id)
        claims = store.list_claims(study_id)
        experiments = store.list_experiments(study_id)
        sessions = store.list_sessions_by_study(study_id)

    if checklist is None:
        checklist = build_checklist(study, cohorts, plans, claims, experiments, sessions)
    readiness = publication_readiness(home_path, study_id)
    files: list[PackageFile] = []
    with ResearchStore(home_path) as research:
        for session in sessions:
            for artifact in research.list_artifacts(session.session_id):
                source = Path(artifact.path)
                if not source.is_file():
                    continue
                session_dir = artifacts_dir / session.session_id
                session_dir.mkdir(exist_ok=True)
                dest = session_dir / f"{artifact.kind.value}{source.suffix.lower()}"
                shutil.copy2(source, dest)
                files.append(
                    PackageFile(
                        kind=artifact.kind.value,
                        source=str(source),
                        path=str(dest),
                        sha256=_sha256(dest),
                    )
                )

    checklist_json = target / "strobe_checklist.json"
    checklist_json.write_text(
        json.dumps(
            checklist.model_dump(mode="json", by_alias=True),
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    checklist_md = target / "strobe_checklist.md"
    checklist_md.write_text(checklist_markdown(checklist), encoding="utf-8")
    for path in (checklist_json, checklist_md):
        files.append(
            PackageFile(
                kind="checklist",
                source=str(path),
                path=str(path),
                sha256=_sha256(path),
            )
        )

    blockers = [
        f"{gate['id']}: {blocker}"
        for gate in readiness.get("gates", [])
        for blocker in gate.get("blockers", [])
    ]
    package = SubmissionPackage(
        study_id=study_id,
        generated_at=datetime.now(UTC).isoformat(),
        output_dir=str(target),
        checklist=checklist,
        readiness=readiness,
        files=files,
        blockers=blockers,
        checklist_review=dict(checklist_review or {}),
        data_availability=(
            "Data are local; availability must be decided by the human (D0-D2 only for export)."
        ),
        code_availability=(
            "Analysis code and versions are recorded in run records; publication packaging "
            "must reference the exact commit and environment lock."
        ),
    )
    manifest = target / "submission_manifest.json"
    manifest.write_text(
        json.dumps(package.model_dump(mode="json", by_alias=True), ensure_ascii=False, indent=2)
        + "\n",
        encoding="utf-8",
    )
    return package
