"""Agent harness adapters (L2): generate installable guidance from bacmap's L1 content.

The source of truth is bacmap itself: MCP server instructions, ``bacmap_role_<role>``
prompts and ``skill://bacmap/<role>/SKILL.md`` resources.  This module only produces
thin, versioned files for harnesses that cannot (or do not) inject those automatically.

Nothing here is a security boundary.  Plan confirmation, MCP profiles, gates and data
classes stay server-side (ADR-12/16/21).
"""

from __future__ import annotations

