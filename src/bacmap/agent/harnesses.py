_HARNESS_BY_NAME = {spec.name: spec for spec in _HARNESSES}


def list_harnesses() -> list[HarnessSpec]:
    return list(_HARNESSES)


def get_harness(name: str) -> HarnessSpec:
    spec = _HARNESS_BY_NAME.get(name.strip().lower())
    if spec is None:
        raise InstallError(
            f"unknown harness {name!r}; choose from {', '.join(sorted(_HARNESS_BY_NAME))}"
        )
    return spec


def _one_line(text: str) -> str:
    return " ".join(text.split())


def instructions_markdown(
    spec: HarnessSpec, *, inline_roles: list[str] | None = None
) -> str:
    """Portable instructions file generated from the same content the MCP server serves.

    Some harnesses (for example Pi in non-interactive mode) do not inject skills or MCP
    resources into the model context. ``inline_roles`` appends the role bodies so the
    guidance still reaches the agent without relying on skill discovery.
    """
    roles = roledef.list_roles()
    for role in inline_roles or []:
        if role not in roles:
            raise InstallError(
                f"unknown role {role!r}; choose from {', '.join(roles)}"
            )
    lines = [
        f"<!-- {GENERATED_MARKER} {__version__}; source: bacmap agent export; do not edit -->",
        "# bacmap operating rules",
        "",
        external_operating_rules(),
        "",
        "## Role guides",
        "",
        "Fetch the live copy from MCP before relying on it; these are guidance, not permissions.",
        "",
        "| Role | MCP prompt | MCP resource |",
        "|---|---|---|",
    ]
    for role in roles:
        lines.append(
            f"| `{role}` | `bacmap_role_{role}` | `skill://bacmap/{role}/SKILL.md` |"
        )
    if inline_roles:
        lines += ["", "## Inlined role guides", ""]
        for role in inline_roles:
            lines += [f"### {role}", "", roledef.load_skill(role), ""]
    lines += [
        "",
        "## Refresh",
        "",
        f"Regenerate with `bacmap agent install --harness {spec.name}`; "
        f"check drift with `bacmap agent doctor`.",
        "",
    ]
    return "\n".join(lines)


def mcp_config_example(spec: HarnessSpec) -> str:
    """A copy-paste MCP configuration snippet (never written automatically)."""
    if spec.config_format == "yaml" and spec.name == "hermes":
        return (
            "# ~/.hermes/config.yaml\n"
            "mcp_servers:\n"
            "  bacmap:\n"
            "    command: /path/to/bacmap\n"
            '    args: ["start", "mcp"]\n'
        )
    if spec.config_format == "yaml" and spec.name == "dsh":
        return (
            "# $DSH_HOME/profiles/<profile>/cordis.patch.yml\n"
            "- insert:\n"
            "  - id: mcp-bacmap\n"
            "    name: '@deepseek-ai/dsh-mcp-client'\n"
            "    config:\n"
            "      serverName: bacmap\n"
            "      transport: stdio\n"
            "      command: /path/to/bacmap\n"
            "      args: ['start', 'mcp']\n"
            "      failOnStartupError: true\n"
        )
    if spec.config_format == "toml":
        return (
            "# ~/.codex/config.toml\n"
            "[mcp_servers.bacmap]\n"
            'command = "/path/to/bacmap"\n'
            'args = ["start", "mcp"]\n'
        )
    if spec.name == "opencode":
        return (
            '// opencode.json\n'
            '{"mcp": {"bacmap": {"type": "local", '
            '"command": ["/path/to/bacmap", "start", "mcp"], "enabled": true}}}\n'
        )
    return (
        '// generic MCP client (stdio)\n'
        '{"mcpServers": {"bacmap": {"command": "/path/to/bacmap", '
        '"args": ["start", "mcp"]}}}\n'
    )


def export_skill(role: str) -> str:
    """Return the portable agentskills.io SKILL.md for a role."""
    if role not in roledef.list_roles():
        raise InstallError(
            f"unknown role {role!r}; choose from {', '.join(roledef.list_roles())}"
        )
    return roledef.skill_markdown(role)


class InstalledFile(BaseModel):
    path: str
    sha256: str


class InstallResult(BaseModel):
    model_config = ConfigDict(populate_by_name=True)

    schema_name: Literal["bacmap.agent_install/1"] = Field(
        default=MANIFEST_SCHEMA, alias="schema"
    )
    harness: str
    scope: str
    bacmap_version: str
    base: str
    instructions: str
    manifest: str
    skills: list[str] = Field(default_factory=list)
    inline_roles: list[str] = Field(default_factory=list)
    files: list[InstalledFile] = Field(default_factory=list)


class DoctorResult(BaseModel):
    model_config = ConfigDict(populate_by_name=True)

    schema_name: Literal["bacmap.agent_doctor/1"] = Field(
        default="bacmap.agent_doctor/1", alias="schema"
    )
    ok: bool
    base: str
    manifest: str
    harness: str = ""
    bacmap_version: str = ""
    installed_version: str = ""
    errors: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)


def _sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _base_dir(scope: str, target: str | Path | None) -> Path:
    if target is not None and str(target).strip():
        return Path(target).expanduser().resolve()
    if scope == "project":
        return Path.cwd().resolve()
    if scope == "user":
        return Path.home().resolve()
    raise InstallError(f"unknown scope {scope!r}; use 'project' or 'user'")


def install(
    harness: str,
    *,
    scope: str = "project",
    target: str | Path | None = None,
    with_skills: bool = False,
    inline_roles: list[str] | None = None,
    force: bool = False,
) -> InstallResult:
    """Write the generated instructions (and optional portable skills) into a harness base."""
    spec = get_harness(harness)
    if scope not in spec.instructions:
        raise InstallError(
            f"harness {spec.name!r} has no {scope!r} instructions path; "
            f"choose from {', '.join(sorted(spec.instructions))}"
        )
    base = _base_dir(scope, target)
    rel = Path(spec.instructions[scope])
    dest = base / rel
    content = instructions_markdown(spec, inline_roles=inline_roles)
    if dest.exists():
        existing = dest.read_text(encoding="utf-8", errors="replace")
        if GENERATED_MARKER not in existing and not force:
            raise InstallError(
                f"refusing to overwrite user file {dest}; pass --force to replace it"
            )
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(content, encoding="utf-8")

    files: list[InstalledFile] = [
        InstalledFile(path=str(dest), sha256=_sha256_text(content))
    ]
    skills: list[str] = []
    if with_skills:
        # 2026-11 实测约定：有约定目录的 harness 直写（Hermes ~/.hermes/skills、
        # Pi ~/.pi/agent/skills、OpenCode/通用 ~/.agents/skills），其余保持
        # .bacmap/skills 便携副本——doctor 按 manifest 记录的实际路径校验。
        skills_rel = Path(spec.skills.get(scope) or SKILLS_REL)
        for role in roledef.list_roles():
            skill_path = base / skills_rel / role / "SKILL.md"
            skill_path.parent.mkdir(parents=True, exist_ok=True)
            text = export_skill(role)
            skill_path.write_text(text, encoding="utf-8")
            files.append(InstalledFile(path=str(skill_path), sha256=_sha256_text(text)))
            skills.append(str(skill_path))

    manifest_path = base / MANIFEST_NAME
    result = InstallResult(
        harness=spec.name,
        scope=scope,
        bacmap_version=__version__,
        base=str(base),
        instructions=str(dest),
        manifest=str(manifest_path),
        skills=skills,
        inline_roles=list(inline_roles or []),
        files=files,
    )
    manifest = json.dumps(
        result.model_dump(mode="json", by_alias=True), ensure_ascii=False, indent=2
    )
    manifest_path.write_text(manifest + "\n", encoding="utf-8")
    return result


def doctor(target: str | Path | None = None) -> DoctorResult:
    """Verify an installed adapter against the current bacmap content (drift check)."""
    base = Path(target).expanduser().resolve() if target is not None else Path.cwd().resolve()
    manifest_path = base / MANIFEST_NAME
    if not manifest_path.is_file():
        return DoctorResult(
            ok=False,
            base=str(base),
            manifest=str(manifest_path),
            errors=[f"no install manifest at {manifest_path}"],
        )
    try:
        raw = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return DoctorResult(
            ok=False,
            base=str(base),
            manifest=str(manifest_path),
            errors=[f"invalid install manifest: {exc}"],
        )
    if not isinstance(raw, dict) or raw.get("schema") != MANIFEST_SCHEMA:
        return DoctorResult(
            ok=False,
            base=str(base),
            manifest=str(manifest_path),
            errors=["unsupported install manifest schema"],
        )

    errors: list[str] = []
    warnings: list[str] = []
    harness = str(raw.get("harness") or "")
    installed_version = str(raw.get("bacmap_version") or "")
    for entry in raw.get("files") or []:
        if not isinstance(entry, dict):
            continue
        path = Path(str(entry.get("path") or ""))
        expected = str(entry.get("sha256") or "")
        if not path.is_file():
            errors.append(f"missing file: {path}")
            continue
        actual = _sha256_file(path)
        if expected and actual != expected:
            errors.append(f"modified file: {path}")
    if installed_version != __version__:
        warnings.append(
            f"installed by bacmap {installed_version or '?'}; current {__version__}; "
            "re-run `bacmap agent install`"
        )
    if harness:
        try:
            spec = get_harness(harness)
        except InstallError:
            errors.append(f"unknown harness in manifest: {harness}")
        else:
            instructions_path = Path(str(raw.get("instructions") or ""))
            if instructions_path.is_file():
                inline = raw.get("inline_roles") or []
                inline_roles = [str(role) for role in inline] if isinstance(inline, list) else []
                expected_text = instructions_markdown(spec, inline_roles=inline_roles)
                if instructions_path.read_text(encoding="utf-8") != expected_text:
                    warnings.append(
                        f"instructions differ from current bacmap content: {instructions_path}"
                    )
    return DoctorResult(
        ok=not errors,
        base=str(base),
        manifest=str(manifest_path),
        harness=harness,
        bacmap_version=__version__,
        installed_version=installed_version,
        errors=errors,
        warnings=warnings,
    )
