MANIFEST_NAME = ".bacmap-agent.json"
MANIFEST_SCHEMA: Literal["bacmap.agent_install/1"] = "bacmap.agent_install/1"
SKILLS_REL = Path(".bacmap") / "skills"
GENERATED_MARKER = "generated by bacmap"


class InstallError(Exception):
    """Raised when an install target cannot be written safely."""


class HarnessSpec(BaseModel):
    """One supported harness and where its generated files go."""

    model_config = ConfigDict(frozen=True)

    name: str
    display_name: str
    instructions: dict[str, str] = Field(
        description="scope (project/user) → path relative to the install base"
    )
    config_format: Literal["yaml", "json", "toml", "none"] = "none"
    config_path: dict[str, str] = Field(default_factory=dict)
    skills: dict[str, str] = Field(
        default_factory=dict,
        description=(
            "scope → skills directory relative to the install base (2026-11 "
            "per-harness conventions, verified on live installs). Empty/unlisted "
            "scopes fall back to the portable .bacmap/skills copy."
        ),
    )
    notes: str = ""


